// Generates every icon ShiftFlow needs (web/PWA, Android launcher, store) from tools/brand/mark.mjs.
// Usage:  node tools/brand/build-icons.mjs
// Needs Playwright with Chromium available (npm i -g playwright && npx playwright install chromium).
import { createRequire } from 'module';
import { mkdirSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { iconSvg, faviconSvg, markGeometry } from './mark.mjs';

const require = createRequire(import.meta.url);
let playwright;
try { playwright = require('playwright'); }
catch { playwright = require(require('child_process').execSync('node -e "process.stdout.write(require.resolve(\'playwright\'))"', { cwd: '/' }).toString()); }

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = (p) => { const f = join(ROOT, p); mkdirSync(dirname(f), { recursive: true }); return f; };

const browser = await playwright.chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 1 });

async function png(svg, size, file, { circle = false, opaque = false } = {}) {
  const clip = circle ? 'border-radius:50%;overflow:hidden;' : '';
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(`<html><body style="margin:0;background:transparent">
    <div style="width:${size}px;height:${size}px;${clip}">${svg.replace(/width="\d+" height="\d+"/, `width="${size}" height="${size}"`)}</div></body></html>`);
  await page.screenshot({ path: out(file), omitBackground: !opaque, clip: { x: 0, y: 0, width: size, height: size } });
}

// ---- Web / PWA -------------------------------------------------------------
writeFileSync(out('web/icons/icon.svg'), iconSvg('rounded', 512));
writeFileSync(out('web/icons/maskable.svg'), iconSvg('full', 512));
writeFileSync(out('web/icons/favicon.svg'), faviconSvg());
await png(iconSvg('rounded'), 192, 'web/icons/icon-192.png');
await png(iconSvg('rounded'), 512, 'web/icons/icon-512.png');
await png(iconSvg('full'), 192, 'web/icons/maskable-192.png', { opaque: true });
await png(iconSvg('full'), 512, 'web/icons/maskable-512.png', { opaque: true });
await png(iconSvg('full'), 180, 'web/icons/apple-touch-icon.png', { opaque: true });
await png(faviconSvg().replace('<svg ', '<svg width="32" height="32" '), 32, 'web/icons/favicon-32.png');

// ---- Android launcher --------------------------------------------------------
const densities = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
for (const [d, k] of Object.entries(densities)) {
  const res = `android/app/src/main/res/mipmap-${d}`;
  await png(iconSvg('rounded'), Math.round(48 * k), `${res}/ic_launcher.png`);
  await png(iconSvg('full'), Math.round(48 * k), `${res}/ic_launcher_round.png`, { circle: true });
  await png(iconSvg('fg'), Math.round(108 * k), `${res}/ic_launcher_foreground.png`);
  await png(iconSvg('bg'), Math.round(108 * k), `${res}/ic_launcher_background.png`, { opaque: true });
}

// Monochrome layer (Android 13+ themed icons) as a vector drawable built from the same geometry.
{
  const g = markGeometry();
  const s = 0.66 * 1.08, t = 17 * 1.08; // 100-unit art -> 108dp viewport, same transform as 'fg'
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/build-icons.mjs -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
  <group android:translateX="${t}" android:translateY="${t}" android:scaleX="${s}" android:scaleY="${s}">
    <path android:pathData="${g.d}" android:strokeColor="#FFFFFFFF" android:strokeWidth="${g.sw}"
        android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>
    <path android:fillColor="#FFFFFFFF"
        android:pathData="M${g.cx - g.r},${g.cy} a${g.r},${g.r} 0 1,0 ${g.r * 2},0 a${g.r},${g.r} 0 1,0 ${-g.r * 2},0"/>
  </group>
</vector>
`;
  writeFileSync(out('android/app/src/main/res/drawable/ic_launcher_monochrome.xml'), xml);
}

// ---- Store ---------------------------------------------------------------------
await png(iconSvg('full'), 512, 'store/graphics/icon-512.png', { opaque: true });

await browser.close();
console.log('icons generated');
